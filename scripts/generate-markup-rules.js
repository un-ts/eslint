/**
 * Regenerates the markuplint rule-name manifest used by `eslint-plugin-markup`.
 *
 * The list cannot be imported at runtime: `@markuplint/rules` is ESM-only and has no `require`
 * entry, while this package also ships CommonJS, so a static import would break that build. It is
 * generated here and committed instead.
 *
 * Run with `node scripts/generate-markup-rules.js`.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'

import rules from '@markuplint/rules'

const names = Object.keys(rules).sort()
const target = path.resolve(
  import.meta.dirname,
  '../packages/markup/src/generated-rules.ts',
)

writeFileSync(
  target,
  `/**
 * The markuplint rules this plugin exposes as ESLint rules, generated by
 * \`scripts/generate-markup-rules.js\` from \`@markuplint/rules\`.
 *
 * Do not edit by hand; run the script after upgrading markuplint.
 */
export const MARKUPLINT_RULE_NAMES: readonly string[] = [
${names.map(name => `  '${name}',`).join('\n')}
]
`,
)

console.log(
  `Wrote ${names.length} rule names to ${path.relative(process.cwd(), target)}`,
)
